import fs from 'node:fs';
import { chromium } from '@playwright/test';
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 256, height: 256 }, deviceScaleFactor: 1 });
await page.setContent('<style>html,body{margin:0;background:transparent}svg{display:block}</style>' + fs.readFileSync('assets/icon.svg', 'utf8'));
await page.screenshot({ path: 'assets/icon.png', omitBackground: true });
await browser.close();
const png = fs.readFileSync('assets/icon.png');
const header = Buffer.alloc(22);
header.writeUInt16LE(1, 2); header.writeUInt16LE(1, 4);
header[6] = 0; header[7] = 0; header.writeUInt16LE(1, 10); header.writeUInt16LE(32, 12);
header.writeUInt32LE(png.length, 14); header.writeUInt32LE(22, 18);
fs.writeFileSync('assets/icon.ico', Buffer.concat([header, png]));
console.log('Original Pulse PNG/ICO assets generated.');
