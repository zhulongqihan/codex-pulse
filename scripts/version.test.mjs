import assert from 'node:assert/strict';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { basename, dirname, isAbsolute, join, relative, resolve } from 'node:path';
import { test } from 'node:test';
import { pathToFileURL } from 'node:url';
import { VERSION_FILES, applyVersionBump, bumpVersion, checkVersions, nextVersion, parseVersion, planVersionBump } from './version.mjs';

const testRoot = resolve(import.meta.dirname, '../.local/version-tests');
const command = resolve(import.meta.dirname, 'version.mjs');
mkdirSync(testRoot, { recursive: true });

function fixture(t, version = '0.4.0') {
  const root = mkdtempSync(join(testRoot, 'fixture-'));
  t.after(() => {
    // Remove only an immediate, owned fixture directory inside this checkout's local cache.
    const child = relative(testRoot, root);
    assert(!isAbsolute(child) && !child.startsWith('..') && !child.includes('/') && !child.includes('\\'));
    assert(basename(root).startsWith('fixture-'));
    rmSync(root, { recursive: true, force: true });
  });
  const contents = {
    'package.json': '\uFEFF' + JSON.stringify({ name: 'codex-pulse', fixture: { version: '9.8.7' }, version, scripts: { check: 'keep me' } }, null, 2).replaceAll('\n', '\r\n') + '\r\n',
    'src-tauri/tauri.conf.json': JSON.stringify({ productName: 'Codex Pulse', app: { version: '9.8.7' }, version }, null, 2) + '\n',
    'src-tauri/Cargo.toml': `# Package versions below must stay untouched.\n[package]\nname = 'codex-pulse'\nversion = '${version}' # application\n\n[dependencies]\nsome-crate = { version = "${version}" }\n\n[package.metadata.fixture]\nversion = "9.8.7"\n`,
    'src-tauri/Cargo.lock': `# Generated by Cargo.\r\nversion = 4\r\n\r\n[[package]]\r\nname = "before"\r\nversion = "${version}"\r\n\r\n[[package]]\r\nname = "codex-pulse"\r\nversion = "${version}"\r\ndependencies = [\r\n "before",\r\n "after",\r\n]\r\n\r\n[[package]]\r\nname = "after"\r\nversion = "${version}"\r\n`,
  };
  for (const [name, text] of Object.entries(contents)) {
    const path = join(root, name);
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, text, 'utf8');
  }
  return { root, contents };
}

function snapshot(root) {
  return Object.fromEntries(VERSION_FILES.map(name => [name, readFileSync(join(root, name))]));
}

test('checks the application versions without reading nested metadata or Cargo lock format as the version', t => {
  const { root } = fixture(t);
  const before = snapshot(root);
  const checked = checkVersions(root);
  assert.equal(checked.version, '0.4.0');
  assert.deepEqual(checked.files.map(file => file.relativePath), VERSION_FILES);
  assert.deepEqual(snapshot(root), before);
});

test('updates only the four own version values and preserves BOM, comments, line endings and other crates', t => {
  const { root, contents } = fixture(t);
  const result = bumpVersion(root, 'patch');
  assert.equal(result.to, '0.4.1');
  assert.equal(result.dryRun, false);
  assert.equal(checkVersions(root).version, '0.4.1');
  assert.equal(readFileSync(join(root, 'package.json'), 'utf8'), contents['package.json'].replace('"version": "0.4.0"', '"version": "0.4.1"'));
  assert.equal(readFileSync(join(root, 'src-tauri/tauri.conf.json'), 'utf8'), contents['src-tauri/tauri.conf.json'].replace('"version": "0.4.0"', '"version": "0.4.1"'));
  assert.equal(readFileSync(join(root, 'src-tauri/Cargo.toml'), 'utf8'), contents['src-tauri/Cargo.toml'].replace("version = '0.4.0' # application", "version = '0.4.1' # application"));
  assert.equal(readFileSync(join(root, 'src-tauri/Cargo.lock'), 'utf8'), contents['src-tauri/Cargo.lock'].replace('name = "codex-pulse"\r\nversion = "0.4.0"', 'name = "codex-pulse"\r\nversion = "0.4.1"'));
});

test('supports minor, major and explicit strictly increasing stable versions', () => {
  assert.equal(nextVersion('0.4.9', 'minor'), '0.5.0');
  assert.equal(nextVersion('0.4.9', 'major'), '1.0.0');
  assert.equal(nextVersion('0.4.9', '1.2.3'), '1.2.3');
  assert.equal(nextVersion('0.4.9', '0.4.10'), '0.4.10');
  assert.equal(nextVersion('1.99.99', '2.0.0'), '2.0.0');
});

test('rejects same versions, downgrades and unsupported inputs before writing', t => {
  const { root } = fixture(t);
  const before = snapshot(root);
  for (const target of ['0.4.0', '0.3.99', '0.0.1', 'v0.4.1', '0.4.1-beta.1', '0.4.1+build.1', '00.4.1', '0.04.1', '0.4', '0.4.1.2', '4294967296.0.0', '--help', 'unknown']) {
    assert.throws(() => bumpVersion(root, target), undefined, target);
    assert.deepEqual(snapshot(root), before, target);
  }
  assert.throws(() => nextVersion('1.2.4294967295', 'patch'), /u32/);
  assert.throws(() => parseVersion('1.2.3\n'), /Unsupported/);
});

test('dry run lists every intended manifest and changes no files', t => {
  const { root } = fixture(t);
  const before = snapshot(root);
  assert.deepEqual(bumpVersion(root, 'minor', { dryRun: true }), { from: '0.4.0', to: '0.5.0', files: [...VERSION_FILES], dryRun: true });
  assert.deepEqual(snapshot(root), before);
});

test('refuses a mismatch or malformed manifest before invoking the writer', t => {
  for (const [name, transform, message] of [
    ['src-tauri/Cargo.lock', text => text.replace('name = "codex-pulse"\r\nversion = "0.4.0"', 'name = "codex-pulse"\r\nversion = "0.3.0"'), /Version mismatch/],
    ['src-tauri/tauri.conf.json', () => '{ broken json', /Cannot parse/],
    ['package.json', text => text.replace('"name": "codex-pulse"', '"name": "another-app"'), /must describe/],
    ['src-tauri/Cargo.toml', text => text.replace("version = '0.4.0' # application", "version = '0.4.0-beta.1' # application"), /Unsupported version/],
  ]) {
    const { root } = fixture(t);
    const file = join(root, name);
    writeFileSync(file, transform(readFileSync(file, 'utf8')), 'utf8');
    const before = snapshot(root);
    let writes = 0;
    assert.throws(() => bumpVersion(root, 'patch', { writeFile: () => { writes++; } }), message);
    assert.equal(writes, 0);
    assert.deepEqual(snapshot(root), before);
  }
});

test('rejects duplicate own package entries instead of changing an ambiguous lockfile', t => {
  const { root } = fixture(t);
  const file = join(root, 'src-tauri/Cargo.lock');
  writeFileSync(file, readFileSync(file, 'utf8') + '\n[[package]]\nname = "codex-pulse"\nversion = "0.4.0"\n', 'utf8');
  const before = snapshot(root);
  assert.throws(() => bumpVersion(root, 'patch'), /exactly one codex-pulse/);
  assert.deepEqual(snapshot(root), before);
});

test('rejects concurrent manifest edits before applying any part of a prepared plan', t => {
  const { root } = fixture(t);
  const plan = planVersionBump(root, 'patch');
  const path = join(root, 'src-tauri/tauri.conf.json');
  writeFileSync(path, readFileSync(path, 'utf8').replace('"productName": "Codex Pulse"', '"productName": "Concurrent edit"'), 'utf8');
  const before = snapshot(root);
  assert.throws(() => applyVersionBump(plan), /changed after planning/);
  assert.deepEqual(snapshot(root), before);
});

test('restores all original bytes when a later write has already partially truncated its file', t => {
  const { root } = fixture(t);
  const before = snapshot(root);
  const failureFile = join(root, 'src-tauri/Cargo.toml');
  let failed = false;
  assert.throws(() => bumpVersion(root, 'patch', {
    writeFile(path, text, encoding) {
      if (path === failureFile && !failed) {
        failed = true;
        writeFileSync(path, 'partial write', encoding);
        throw new Error('Simulated disk write failure');
      }
      writeFileSync(path, text, encoding);
    },
  }), /original files were restored: Simulated disk write failure/);
  assert.equal(failed, true);
  assert.deepEqual(snapshot(root), before);
  assert.equal(checkVersions(root).version, '0.4.0');
});

test('reports an incomplete rollback if the filesystem also rejects restoration', t => {
  const { root } = fixture(t);
  const failureFile = join(root, 'src-tauri/Cargo.toml');
  const before = snapshot(root);
  let failed = false;
  assert.throws(() => bumpVersion(root, 'patch', {
    writeFile(path, text, encoding) {
      if (path === failureFile) {
        if (!failed) { failed = true; writeFileSync(path, 'partial write', encoding); }
        throw new Error('Simulated persistent filesystem failure');
      }
      writeFileSync(path, text, encoding);
    },
  }), error => error instanceof AggregateError && /rollback was incomplete/.test(error.message) && /src-tauri\/Cargo.toml/.test(error.message));
  for (const name of ['package.json', 'src-tauri/tauri.conf.json', 'src-tauri/Cargo.lock']) {
    assert.deepEqual(readFileSync(join(root, name)), before[name]);
  }
});

test('does not apply a modified plan that would change unrelated metadata', t => {
  const { root } = fixture(t);
  const before = snapshot(root);
  const plan = planVersionBump(root, 'patch');
  plan.files[0].after = plan.files[0].after.replace('"check": "keep me"', '"check": "changed"');
  assert.throws(() => applyVersionBump(plan), /unexpected changes/);
  assert.deepEqual(snapshot(root), before);
});

test('CLI uses its working directory and importing the module performs no action', t => {
  const { root } = fixture(t, '3.2.1');
  const before = snapshot(root);
  const imported = execFileSync(process.execPath, ['--input-type=module', '-e', `await import(${JSON.stringify(pathToFileURL(command).href)});`], { cwd: root, encoding: 'utf8' });
  assert.equal(imported, '');
  assert.deepEqual(snapshot(root), before);
  const checked = execFileSync(process.execPath, [command, 'check'], { cwd: root, encoding: 'utf8' });
  assert.match(checked, /Version check passed: 3\.2\.1 \(4 files\)/);
  const preview = execFileSync(process.execPath, [command, 'bump', 'patch', '--dry-run'], { cwd: root, encoding: 'utf8' });
  assert.match(preview, /Dry run: 3\.2\.1 -> 3\.2\.2/);
  assert.match(preview, /No files were written/);
  assert.deepEqual(snapshot(root), before);
  execFileSync(process.execPath, [command, 'bump', 'minor'], { cwd: root, encoding: 'utf8' });
  assert.equal(checkVersions(root).version, '3.3.0');
});

test('CLI exits unsuccessfully for invalid arguments without writing', t => {
  const { root } = fixture(t);
  const before = snapshot(root);
  for (const args of [[], ['check', '--dry-run'], ['bump'], ['bump', 'patch', '--extra'], ['bump', 'patch', '--dry-run', '--dry-run'], ['bump', '0.4.0']]) {
    const result = spawnSync(process.execPath, [command, ...args], { cwd: root, encoding: 'utf8' });
    assert.equal(result.status, 1, args.join(' '));
    assert.deepEqual(snapshot(root), before);
  }
});
